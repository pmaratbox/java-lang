public class MathFunctions {
    public static void main(String[] args) {
        System.out.println("sqrt: " + (int) Math.sqrt(16));
        System.out.println("pow: " + (int) Math.pow(2, 10));
        System.out.println("abs: " + Math.abs(-5));
        System.out.println("max: " + Math.max(3, 9));
    }
}
