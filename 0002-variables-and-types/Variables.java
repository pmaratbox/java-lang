public class Variables {
    public static void main(String[] args) {
        int n = 42;
        double pi = 3.14;
        String greeting = "hello";
        boolean flag = true;

        System.out.println("int: " + n);
        System.out.println("float: " + pi);
        System.out.println("string: " + greeting);
        System.out.println("bool: " + flag);
    }
}
